func main() {
	if len(os.Args) < 2 {
		printHelp()
		os.Exit(0)
	}

	cfg, err := config.Load()
	if err != nil {
		fmt.Fprintf(os.Stderr, "Warning: failed to load config: %v\n", err)
		cfg = config.DefaultConfig()
	}

	firstArg := os.Args[1]

	// Internal worker execution
	if firstArg == "__worker" {
		if len(os.Args) < 3 {
			fmt.Fprintln(os.Stderr, "Error: missing job ID for worker")
			os.Exit(1)
		}
		if err := supervisor.ExecuteWorker(os.Args[2]); err != nil {
			fmt.Fprintf(os.Stderr, "Worker error: %v\n", err)
			os.Exit(1)
		}
		os.Exit(0)
	}

	// Subcommands
	switch firstArg {
	case "version", "--version", "-v":
		fmt.Printf("Bifrost v%s\n", version)
		return
	case "help", "--help", "-h":
		printHelp()
		return
	case "realms", "doctor":
		cmdDoctor()
		return
	case "config":
		cmdConfig(cfg)
		return
	case "list", "ps":
		cmdList()
		return
	case "status":
		if len(os.Args) < 3 {
			fmt.Fprintln(os.Stderr, "Error: missing JOB_ID. Usage: bifrost status <JOB_ID>")
			os.Exit(1)
		}
		cmdStatus(os.Args[2])
		return
	case "logs", "log":
		cmdLogs(os.Args[2:])
		return
	case "abort", "kill":
		if len(os.Args) < 3 {
			fmt.Fprintln(os.Stderr, "Error: missing JOB_ID. Usage: bifrost abort <JOB_ID>")
			os.Exit(1)
		}
		cmdAbort(os.Args[2])
		return
	case "diff":
		if len(os.Args) < 3 {
			fmt.Fprintln(os.Stderr, "Error: missing JOB_ID. Usage: bifrost diff <JOB_ID>")
			os.Exit(1)
		}
		cmdDiff(os.Args[2])
		return
	case "merge":
		if len(os.Args) < 3 {
			fmt.Fprintln(os.Stderr, "Error: missing JOB_ID. Usage: bifrost merge <JOB_ID>")
			os.Exit(1)
		}
		cmdMerge(os.Args[2], cfg)
		return
	case "clean":
		if len(os.Args) < 3 {
			fmt.Fprintln(os.Stderr, "Error: missing JOB_ID. Usage: bifrost clean <JOB_ID> [--keep-branch]")
			os.Exit(1)
		}
		keepBranch := false
		if len(os.Args) > 3 && os.Args[3] == "--keep-branch" {
			keepBranch = true
		}
		cmdClean(os.Args[2], keepBranch)
		return
	case "prune":
		cmdPrune()
		return
	}

	// Dispatch task
	cmdDispatch(os.Args[1:], cfg)
}

func cmdConfig(cfg *config.Config) {
	p, _ := config.ConfigPath()
	fmt.Printf("🌈 Bifrost Declarative Config (%s):\n", p)
	data, _ := json.MarshalIndent(cfg, "", "  ")
	fmt.Println(string(data))
}

func cmdDoctor() {
	fmt.Println("🌈 Bifrost Realms & Doctor Check:")
	fmt.Println("--------------------------------------------------------------------------------")
	w := tabwriter.NewWriter(os.Stdout, 0, 0, 3, ' ', 0)
	fmt.Fprintln(w, "REALM\tNAME\tSTATUS\tDETAILS")

	ctx, cancel := context.WithTimeout(context.Background(), 3*time.Second)
	defer cancel()

	for _, r := range realm.All() {
		avail, details := r.IsAvailable(ctx)
		status := "❌ Unavailable"
		if avail {
			status = "✅ Operational"
		}
		fmt.Fprintf(w, "%s\t%s\t%s\t%s\n", r.ID(), r.Name(), status, details)
	}
	w.Flush()
	fmt.Println("--------------------------------------------------------------------------------")
}

func cmdList() {
	jobs, err := supervisor.ListJobs()
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error listing jobs: %v\n", err)
		os.Exit(1)
	}
	if len(jobs) == 0 {
		fmt.Println("No Bifrost jobs found.")
		return
	}

	w := tabwriter.NewWriter(os.Stdout, 0, 0, 2, ' ', 0)
	fmt.Fprintln(w, "JOB ID\tREALM\tSTATUS\tCREATED\tWORKTREE\tPROMPT")
	for _, j := range jobs {
		wt := "-"
		if j.WorktreeBranch != "" {
			wt = j.WorktreeBranch
		}
		promptPreview := j.Prompt
		if len(promptPreview) > 35 {
			promptPreview = promptPreview[:32] + "..."
		}
		created := j.CreatedAt.Format("01-02 15:04")
		fmt.Fprintf(w, "%s\t%s\t%s\t%s\t%s\t%s\n", j.ID, j.Realm, j.Status, created, wt, promptPreview)
	}
	w.Flush()
}

func cmdStatus(jobID string) {
	j, err := supervisor.GetJob(jobID)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error: %v\n", err)
		os.Exit(1)
	}

	fmt.Printf("Job ID:       %s\n", j.ID)
	fmt.Printf("Realm:        %s\n", j.Realm)
	fmt.Printf("Status:       %s\n", j.Status)
	fmt.Printf("PID:          %d\n", j.PID)
	fmt.Printf("Working Dir:  %s\n", j.WorkDir)
	if j.WorktreeBranch != "" {
		fmt.Printf("Worktree:     %s (%s)\n", j.WorktreeBranch, j.WorktreePath)
	}
	fmt.Printf("Created At:   %s\n", j.CreatedAt.Format(time.RFC1123))
	if j.FinishedAt != nil {
		fmt.Printf("Finished At:  %s (Duration: %s)\n", j.FinishedAt.Format(time.RFC1123), j.FinishedAt.Sub(j.CreatedAt).Round(time.Second))
	}
	fmt.Printf("Log File:     %s\n", j.LogFile)
	if j.Error != "" {
		fmt.Printf("Error:        %s\n", j.Error)
	}
	fmt.Printf("Prompt:       %s\n", j.Prompt)
}

func cmdLogs(args []string) {
	if len(args) == 0 {
		fmt.Fprintln(os.Stderr, "Error: missing JOB_ID. Usage: bifrost logs [-f] <JOB_ID>")
		os.Exit(1)
	}

	follow := false
	jobID := ""
	for _, arg := range args {
		if arg == "-f" || arg == "--follow" {
			follow = true
		} else {
			jobID = arg
		}
	}

	if jobID == "" {
		fmt.Fprintln(os.Stderr, "Error: missing JOB_ID. Usage: bifrost logs [-f] <JOB_ID>")
		os.Exit(1)
	}

	if follow {
		ctx, cancel := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
		defer cancel()
		if err := supervisor.FollowLog(ctx, jobID, os.Stdout); err != nil {
			fmt.Fprintf(os.Stderr, "Log streaming error: %v\n", err)
			os.Exit(1)
		}
	} else {
		if err := supervisor.PrintLog(jobID, 0); err != nil {
			fmt.Fprintf(os.Stderr, "Error reading logs: %v\n", err)
			os.Exit(1)
		}
	}
}

func cmdAbort(jobID string) {
	if err := supervisor.AbortJob(jobID); err != nil {
		fmt.Fprintf(os.Stderr, "Error aborting job: %v\n", err)
		os.Exit(1)
	}
	fmt.Printf("Job '%s' aborted successfully.\n", jobID)
}

func cmdDiff(jobID string) {
	j, err := supervisor.GetJob(jobID)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error: %v\n", err)
		os.Exit(1)
	}
	if j.WorktreeBranch == "" {
		fmt.Fprintf(os.Stderr, "Job '%s' was not run inside an isolated worktree.\n", jobID)
		os.Exit(1)
	}

	diff, err := workspace.Diff(context.Background(), j.RepoRoot, j.WorktreeBranch)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error computing diff: %v\n", err)
		os.Exit(1)
	}
	if strings.TrimSpace(diff) == "" {
		fmt.Println("No modifications detected in worktree branch.")
		return
	}
	fmt.Print(diff)
}

func cmdMerge(jobID string, cfg *config.Config) {
	j, err := supervisor.GetJob(jobID)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error: %v\n", err)
		os.Exit(1)
	}
	if j.WorktreeBranch == "" {
		fmt.Fprintf(os.Stderr, "Job '%s' was not run inside an isolated worktree.\n", jobID)
		os.Exit(1)
	}

	out, err := workspace.Merge(context.Background(), j.RepoRoot, j.WorktreeBranch)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error merging branch: %v\n%s\n", err, out)
		os.Exit(1)
	}
	fmt.Printf("✅ Successfully merged worktree branch '%s' into current branch!\n", j.WorktreeBranch)

	if cfg.Worktree.AutoCleanupOnMerge {
		fmt.Printf("🧹 Auto-cleaning worktree for job '%s'...\n", jobID)
		_ = supervisor.CleanJob(jobID, true)
		fmt.Println("✨ Worktree cleaned successfully.")
	}
}

func cmdClean(jobID string, keepBranch bool) {
	deleteBranch := !keepBranch
	if err := supervisor.CleanJob(jobID, deleteBranch); err != nil {
		fmt.Fprintf(os.Stderr, "Error cleaning job: %v\n", err)
		os.Exit(1)
	}
	fmt.Printf("🧹 Worktree for job '%s' cleaned successfully.\n", jobID)
}

func cmdPrune() {
	count, err := supervisor.PruneJobs(true)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error pruning jobs: %v\n", err)
		os.Exit(1)
	}
	fmt.Printf("🧹 Pruned %d finished job(s), logs, and orphan worktrees.\n", count)
}

func cmdDispatch(args []string, cfg *config.Config) {
	fs := flag.NewFlagSet("dispatch", flag.ExitOnError)
	defaultRealm := cfg.DefaultRealm
	if defaultRealm == "" {
		defaultRealm = "auto"
	}
	realmFlag := fs.String("realm", defaultRealm, "Target realm (agy, opencode, auto)")
	fs.StringVar(realmFlag, "r", defaultRealm, "Short alias for --realm")

	worktreeFlag := fs.Bool("worktree", false, "Isolate in ephemeral Git Worktree")
	fs.BoolVar(worktreeFlag, "w", false, "Short alias for --worktree")

	bgFlag := fs.Bool("bg", false, "Run in background")
	fs.BoolVar(bgFlag, "b", false, "Short alias for --bg")

	modelFlag := fs.String("model", "", "Model override")
	fs.StringVar(modelFlag, "m", "", "Short alias for --model")

	effortFlag := fs.String("effort", "", "Reasoning effort (low, medium, high)")
	fs.StringVar(effortFlag, "e", "", "Short alias for --effort")

	dirFlag := fs.String("dir", "", "Working directory")
	fs.StringVar(dirFlag, "d", "", "Short alias for --dir")

	_ = fs.Parse(args)
	tail := fs.Args()

	if len(tail) == 0 {
		printHelp()
		os.Exit(1)
	}

	prompt := strings.Join(tail, " ")
	currentDir, _ := os.Getwd()
	if *dirFlag != "" {
		currentDir, _ = filepath.Abs(*dirFlag)
	}

	ctx := context.Background()

	// 1. Resolve Realm using priority list from config
	targetRealm, err := realm.ResolveRealm(ctx, *realmFlag, cfg.Priority)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Bridge routing error: %v\n", err)
		os.Exit(1)
	}

	// Apply default model and effort from config if not explicitly set
	finalModel := *modelFlag
	finalEffort := *effortFlag
	if realmCfg, ok := cfg.Realms[targetRealm.ID()]; ok {
		if finalModel == "" && realmCfg.DefaultModel != "" {
			finalModel = realmCfg.DefaultModel
		}
		if finalEffort == "" && realmCfg.DefaultEffort != "" {
			finalEffort = realmCfg.DefaultEffort
		}
	}

	taskID := generateTaskID()
	var wtSession *workspace.WorktreeSession
	targetDir := currentDir

	// 2. Prepare Workspace (Git Worktree isolation)
	if *worktreeFlag {
		fmt.Printf("🌐 Preparing isolated Git Worktree for task '%s'...\n", taskID)
		var err error
		wtSession, err = workspace.PrepareWorktree(ctx, taskID, currentDir)
		if err != nil {
			fmt.Fprintf(os.Stderr, "Worktree error: %v\n", err)
			os.Exit(1)
		}
		targetDir = wtSession.Path
		fmt.Printf("🌿 Worktree mounted: %s (branch: %s)\n", wtSession.Path, wtSession.Branch)
	}

	task := realm.Task{
		ID:         taskID,
		Prompt:     prompt,
		WorkDir:    targetDir,
		Worktree:   *worktreeFlag,
		Background: *bgFlag,
		Model:      finalModel,
		Effort:     finalEffort,
	}

	fmt.Printf("⚡ Bifrost crossing to [%s] with task %s\n", targetRealm.Name(), taskID)

	// 3. Execution
	if *bgFlag {
		job, err := supervisor.SpawnBackground(task, targetRealm, targetDir, wtSession)
		if err != nil {
			fmt.Fprintf(os.Stderr, "Background spawn error: %v\n", err)
			os.Exit(1)
		}
		fmt.Printf("🚀 Agent dispatched in background!\n")
		fmt.Printf("   Task ID: %s (PID: %d)\n", job.ID, job.PID)
		fmt.Printf("   Logs:    bifrost logs -f %s\n", job.ID)
		fmt.Printf("   Status:  bifrost status %s\n", job.ID)
		if *worktreeFlag {
			fmt.Printf("   Review:  bifrost diff %s\n", job.ID)
			fmt.Printf("   Merge:   bifrost merge %s\n", job.ID)
			fmt.Printf("   Clean:   bifrost clean %s\n", job.ID)
		}
		return
	}

	// Foreground Execution
	start := time.Now()
	err = supervisor.RunForeground(ctx, task, targetRealm, targetDir, wtSession)
	duration := time.Since(start).Round(time.Millisecond)

	if err != nil {
		fmt.Fprintf(os.Stderr, "\n❌ Realm execution failed after %s: %v\n", duration, err)
		os.Exit(1)
	}

	fmt.Printf("\n✨ Task completed successfully in %s.\n", duration)
	if *worktreeFlag {
		fmt.Println("--------------------------------------------------------------------------------")
		fmt.Printf("Branch '%s' contains your isolated changes.\n", wtSession.Branch)
		fmt.Printf("To inspect changes: bifrost diff %s\n", taskID)
		fmt.Printf("To merge changes:   bifrost merge %s\n", taskID)
		fmt.Printf("To discard changes: bifrost clean %s\n", taskID)
		fmt.Println("--------------------------------------------------------------------------------")
	}
}
